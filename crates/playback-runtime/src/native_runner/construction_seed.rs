use super::play_fx_config::default_play_fx_selected;
use super::*;

pub(super) struct NativeRunnerConstructionSeed {
    pub(super) now: Instant,
    pub(super) ui: NativeUiState,
    pub(super) hdmi: NativeHdmiConfig,
    pub(super) global_sound: GlobalSoundConfig,
    pub(super) dsp_config: realtime_engine::synth::DspRuntimeConfig,
    pub(super) audio_io: super::audio_io_settings::NativeAudioIoSettings,
    pub(super) bpm: f64,
    pub(super) swing_a: u8,
    pub(super) swing_b: u8,
    pub(super) sync_source: SyncSource,
    pub(super) algorithm_step_pulses: u32,
    pub(super) instruments: Vec<NativeInstrumentSlot>,
    pub(super) sample_availability: Vec<Vec<NativeSampleAvailability>>,
    pub(super) link_layers: Vec<NativeLinkLayer>,
    pub(super) fx_buses: Vec<NativeFxBus>,
    pub(super) global_fx_slots: Vec<String>,
    pub(super) global_fx_params: Vec<Value>,
    pub(super) link_lfos: [NativeLinkLfo; GLOBAL_LFO_COUNT],
    pub(super) param_mods: Vec<NativeParamMods>,
    pub(super) xy_x_binding: Option<NativeParamBinding>,
    pub(super) xy_y_binding: Option<NativeParamBinding>,
    pub(super) aux_auto_map_enabled: bool,
    pub(super) aux_priority: String,
    pub(super) aux_bindings: Vec<Option<NativeAuxBinding>>,
    pub(super) shift_aux_bindings: Vec<Option<NativeAuxBinding>>,
    pub(super) sample_favourite_dirs: Vec<String>,
    pub(super) sample_builtin_favourite_dirs: Vec<String>,
    pub(super) preset_names: Vec<String>,
    pub(super) midi_outputs: Vec<MidiPort>,
    pub(super) midi_inputs: Vec<MidiPort>,
    pub(super) play_mode: PlayMode,
    pub(super) play_fx_selected: Value,
    pub(super) xy_release: String,
    pub(super) xy_smoothing_ms: u16,
    pub(super) xy_invert_x: bool,
    pub(super) xy_invert_y: bool,
    pub(super) voice_stealing_mode: VoiceStealingMode,
    pub(super) auto_save_default: bool,
    pub(super) rolling_backups: bool,
    pub(super) input_events_while_paused: bool,
    pub(super) active_layer_index: usize,
}

impl NativeRunnerConstructionSeed {
    pub(super) fn new(config: &NativeRunnerConfig, ui: NativeUiState, now: Instant) -> Self {
        Self {
            now,
            ui,
            hdmi: NativeHdmiConfig {
                mode: "terminal".into(),
                show_gridlines: false,
                cycle_measures: 4,
                source_layer_index: 0,
            },
            global_sound: config.global_sound.clone(),
            dsp_config: realtime_engine::synth::DspRuntimeConfig::default(),
            audio_io: super::audio_io_settings::NativeAudioIoSettings::new(config),
            bpm: config.bpm,
            swing_a: config.swing_a.clamp(1, 7),
            swing_b: config.swing_b.clamp(1, 7),
            sync_source: config.sync_source.clone(),
            algorithm_step_pulses: DEFAULT_ALGORITHM_STEP_RED,
            instruments: default_instruments(),
            sample_availability: default_sample_availability(),
            link_layers: default_link_layers(),
            fx_buses: default_fx_buses(),
            global_fx_slots: default_global_fx_slots(),
            global_fx_params: default_global_fx_params(),
            link_lfos: std::array::from_fn(|_| NativeLinkLfo::default()),
            param_mods: vec![NativeParamMods::default(); LAYER_COUNT],
            xy_x_binding: None,
            xy_y_binding: None,
            aux_auto_map_enabled: true,
            aux_priority: "manual".into(),
            aux_bindings: vec![None; platform_core::AUX_ENCODER_COUNT],
            shift_aux_bindings: vec![None; platform_core::AUX_ENCODER_COUNT],
            sample_favourite_dirs: Vec::new(),
            sample_builtin_favourite_dirs: config.sample_builtin_favourite_dirs.clone(),
            preset_names: Vec::new(),
            midi_outputs: Vec::new(),
            midi_inputs: Vec::new(),
            play_mode: PlayMode::Mix,
            play_fx_selected: default_play_fx_selected(),
            xy_release: "sample-hold".into(),
            xy_smoothing_ms: DEFAULT_XY_SMOOTHING_MS,
            xy_invert_x: false,
            xy_invert_y: false,
            voice_stealing_mode: VoiceStealingMode::AutoBalanced,
            auto_save_default: false,
            rolling_backups: true,
            input_events_while_paused: true,
            active_layer_index: 0,
        }
    }
}
